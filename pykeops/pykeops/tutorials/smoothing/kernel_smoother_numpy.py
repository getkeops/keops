# Smoothing in 1D with pointwise variance estimation
# -------------------
# Performing a second smoothing in sequence, we can estimate the pointwise variance of the estimator :math:`\hat V_y(x))`
# where the weights are computed using a kernel of our choosing :  
#
# .. math::
#        \hat V_y(x) = \frac{\Sum (y_i-\hat y(x)) K(x, x_i)}{\Sum K(x, x_i)},
#
# This is especially useful when the noise term depends on :math:`y`.

def kernel_smoother(x, y, bandwidth=0.1, grid_size=100, kernel='gaussian'):
    """
    Kernel smoother with single input and single output using KeOps.

    Parameters:
    - x: Independent variable (numpy array)
    - y: Dependent variable (numpy array)
    - bandwidth: Kernel bandwidth parameter
    - grid_size: Number of points for the evaluation grid
    - kernel: 'gaussian', 'quadratic' or custom kernel function

    Returns:
    - grid_x: Grid coordinates
    - smoothed_grid_y: Smoothed output variable on grid
    """

    # Create grid points
    x_min, x_max = x.min(), x.max()
    grid_x = np.linspace(x_min, x_max, grid_size)

    # Create LazyTensors
    x_j = LazyTensor(x[None, :, None])  # Shape: [1, n_samples, 1]
    x_i = LazyTensor(x[:, None, None])  # Shape: [n_samples, 1, 1]
    grid_i = LazyTensor(grid_x[:, None, None])  # Shape: [grid_size, 1, 1]

    # Compute Gaussian kernel weights for grid points
    if kernel == 'gaussian':
        D_ij = ((x_i - x_j)**2).sum(dim=2)  # Shape: [grid_size, n_samples]
        K_ij = (-D_ij / (2 * bandwidth**2)).exp()  # Shape: [grid_size, n_samples]
    # Compute quadratic kernel weights for grid points
    elif kernel == 'quadratic':
        D_ij = ((x_i - x_j)**2).sum(dim=2)  # Shape: [grid_size, n_samples]
        K_ij = (D_ij < bandwidth**2)*(1-D_ij.sqrt()/bandwidth)**2
    else:
        K_ij = kernel(x_i, x_j, bandwidth=bandwidth)

    # Normalize kernel weights (row-wise sum to 1)
    K_ij_sum = K_ij.sum(dim=1)[:, None]
    K_ij = K_ij / K_ij_sum

    # Perform kernel smoothing for output variable on grid
    smoothed_y = K_ij@y
    mse = (y-smoothed_y)**2

    # Compute Gaussian kernel weights for grid points
    if kernel == 'gaussian':
        D_grid_sample = ((grid_i - x_j)**2).sum(dim=2)  # Shape: [grid_size, n_samples]
        K_grid_sample = (-D_grid_sample / (2 * bandwidth**2)).exp()  # Shape: [grid_size, n_samples]
    # Compute quadratic kernel weights for grid points
    elif kernel == 'quadratic':
        D_grid_sample = ((grid_i - x_j)**2).sum(dim=2)  # Shape: [grid_size, n_samples]
        K_grid_sample = (D_grid_sample < bandwidth**2)*(1-D_grid_sample.sqrt()/bandwidth)**2
    else:
        K_grid_sample = kernel(grid_i, x_j, bandwidth=bandwidth)

    # Normalize kernel weights (row-wise sum to 1)
    K_grid_sample_sum = K_grid_sample.sum(dim=1)[:, None]
    K_grid_sample = K_grid_sample / K_grid_sample_sum

    # Perform kernel smoothing for output variable on grid
    smoothed_grid_y = K_grid_sample@y
    grid_mse = K_grid_sample@mse

    return grid_x, smoothed_grid_y, grid_mse

#######################################################################
# Display the model's predictions:
#

def plot_smoothing_results(x, y, grid_x, smoothed_grid_y, grid_mse):
    """
    Plot the original and smoothed data in 2D.

    Parameters:
    - x: Original input variable
    - y: Original output variable
    - grid_x: Grid coordinates
    - smoothed_grid_y: Smoothed output variable on grid
    """
    plt.figure(figsize=(12, 6))

    # Plot original data points
    plt.scatter(x, y, c='red', s=30, alpha=0.7, label='Original Data')

    # Plot smoothed values on grid
    plt.plot(grid_x, smoothed_grid_y, 'b-', linewidth=2, label='Smoothed Function')
    plt.plot(grid_x, smoothed_grid_y+2*np.sqrt(grid_mse), 'b--', linewidth=2, label='Smoothed Function')
    plt.plot(grid_x, smoothed_grid_y-2*np.sqrt(grid_mse), 'b--', linewidth=2, label='Smoothed Function')

    plt.title('Kernel Smoothing Results')
    plt.xlabel('Input (x)')
    plt.ylabel('Output (y)')
    plt.legend()
    plt.grid(True)
    plt.tight_layout()
    plt.show()

