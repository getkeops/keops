# Interpolation in 2D
# -------------------


def kernel_smoother(x, y, bandwidth=1.0, grid_size=100, kernel='gaussian'):
    """
    Kernel smoother with single input and single output using KeOps.

    Parameters:
    - x: Input variable (numpy array or torch tensor)
    - y: Output variable (numpy array or torch tensor)
    - bandwidth: Kernel bandwidth parameter
    - grid_size: Number of points for the grid
    - kernel: 'gaussian', 'quadratic' or custom kernel function

    Returns:
    - xx: First grid coordinate
    - yy: Second grid coordinate
    - bb: Smoothed output variable on grid
    """


    # Create grid points
    x_min, x_max = x[:,0].min(), x[:,0].max()
    y_min, y_max = x[:,1].min(), x[:,1].max()
    grid_x = np.linspace(x_min, x_max, grid_size)
    grid_y = np.linspace(y_min, y_max, grid_size)
    xx, yy = np.meshgrid(grid_x, grid_y)

    G = np.hstack([xx.reshape(-1,1), yy.reshape(-1,1)])

    # Create LazyTensors for efficient computation
    X_i = LazyTensor(x[:, None, :])  # Shape: [n_samples, 1, 2]
    print(X_i.shape)
    X_j = LazyTensor(x[None, :, :])  # Shape: [1, n_samples, 2]
    G_i = LazyTensor(G[:, None, :])  # Shape: [grid_size*grid_size, 1, 2]

    # Compute pairwise squared distances between samples
    D_ij = ((X_i - X_j)**2).sum(dim=2)  # Shape: [n_samples, n_samples]

    # Compute Gaussian kernel weights for grid points
    if kernel == 'gaussian':
        D_grid_sample = ((G_i - X_j)**2).sum(dim=2)  # Shape: [grid_size, n_samples]
        K_grid_sample = (-D_grid_sample / (2 * bandwidth**2)).exp()  # Shape: [grid_size, n_samples]
    # Compute quadratic kernel weights for grid points
    elif kernel == 'quadratic':
        D_grid_sample = ((G_i - X_j)**2).sum(dim=2)  # Shape: [grid_size, n_samples]
        K_grid_sample = (D_grid_sample < bandwidth**2)*(1-D_grid_sample.sqrt()/bandwidth)**2
    else:
        K_grid_sample = kernel(G_i, X_j, bandwidth=bandwidth)

    # Normalize kernel weights (row-wise sum to 1)
    K_grid_sample_sum = K_grid_sample.sum(dim=1)[:, None]  # Using [:, None] instead of keepdim
    K_grid_sample = K_grid_sample / K_grid_sample_sum

    # Perform kernel smoothing for output variable on grid
    bb = K_grid_sample@y


    return xx, yy, bb.reshape(xx.shape)

def plot_smoothing_results(x, b, xx, yy, bb):
    """
    Plot the original and smoothed data in 2D.

    Parameters:
    - x: Original input variable
    - b: Original output variable
    - xx: First grid coordinate
    - yy: Second grid coordinate
    - bb: Smoothed output variable on grid
    """
    plt.figure(figsize=(12, 6))
    plt.pcolormesh(xx, yy, bb, cmap="coolwarm")
    plt.scatter(x[:,0], x[:,1], c=b, s=25000 / len(x), cmap="bwr")
    plt.title('Kernel Smoothing Results')
    plt.tight_layout()
    plt.show()

